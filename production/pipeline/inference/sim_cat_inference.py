# CHECKPOINT / RESUME
# ══════════════════════════════════════════════════════════════════════════
# WHY THIS EXISTS. Pool slots evict long attempts at ~25 h. Measured on
# cluster 70956452 (the cholfix nlive=1000 sweep): of 90 evictions, 88
# landed at >=20 h, with a knee at 25 h -- Kaplan-Meier slot survival is
# 95% past 24 h, 50% past 25 h, 21% past 27 h, 6.6% past 30 h. Before this
# change run_nested() held no state on disk, so an evicted job restarted
# nested sampling from iteration 1. Any run whose from-scratch cost exceeded
# the slot lifetime could therefore NEVER finish, however many times
# periodic_release released it: 32/100 jobs in that sweep were each evicted
# twice at >=24 h having produced nothing. With checkpointing an evicted run
# resumes where it stopped, so total progress accumulates across attempts
# and the wall stops being a ceiling on the achievable run length.
#
# WHERE THE CHECKPOINT LIVES. Next to its final output, i.e. under --outdir
# on the shared filesystem. It must NOT go to the execute node's scratch
# directory, which is destroyed on eviction -- that is the whole failure
# mode this fixes.
#
# WHY A HALF-WRITTEN CHECKPOINT IS NOT A HAZARD. dynesty's save_sampler()
# pickles to <file>.tmp and then os.rename()s it into place, which is atomic
# within a filesystem. An eviction during a checkpoint write therefore
# leaves the PREVIOUS good checkpoint intact, never a truncated one. A
# stray .tmp may survive; it is inert and is ignored here.
#
# WHY 900 s BY DEFAULT. The checkpoint is a pickle of the whole sampler
# (~6-7 MB for these runs) written to NFS. dynesty's own default of 60 s
# would write it ~1500 times over a 25 h attempt for no benefit; at 900 s an
# eviction costs at most 15 min of a multi-hour run, which is noise against
# the ~25 h it used to cost. Override with DYNESTY_CHECKPOINT_EVERY
# (seconds) in the job environment.
#
# RESUME IS SAFE ON AN ALREADY-FINISHED CHECKPOINT: run_nested(resume=True)
# on a static run that has already added its live points warns and returns,
# after which save() below writes the completed result as usual.
CKPT_EVERY = float(os.environ.get("DYNESTY_CHECKPOINT_EVERY", 900.0))


def _run_with_checkpoint(loglike, out_path, tag):
    """Run -- or resume -- one static nested sampling run, then save it.

    Returns the sampler, so callers can still reach .results. The completed
    output is written to out_path and the checkpoint is removed, leaving the
    output directory exactly as it looked before this change.
    """
    ckpt = out_path.with_name(out_path.name + ".ckpt")

    sampler, resuming = None, False
    if ckpt.exists():
        try:
            sampler = NestedSampler.restore(str(ckpt))
        except Exception as exc:
            # A checkpoint that cannot be read is recoverable -- we simply
            # pay for a fresh run -- so warn loudly and carry on rather than
            # failing the job.
            print(f"[catalog {args.catalog_id}] {tag} could not resume from "
                  f"{ckpt.name} ({exc!r}); starting from scratch",
                  file=sys.stderr, flush=True)
            sampler = None
        else:
            resuming = True
            print(f"[catalog {args.catalog_id}] {tag} resuming from "
                  f"{ckpt.name} at iteration {getattr(sampler, 'it', '?')}",
                  flush=True)

    if sampler is None:
        sampler = NestedSampler(loglike, prior_transform, ndims,
                                bound=bound, sample=sample, nlive=nlive)

    # A failure inside run_nested is a real error, not a resume problem, so
    # it is deliberately NOT caught: let the job die visibly with the
    # checkpoint left in place for the next attempt to pick up.
    sampler.run_nested(dlogz=0.1, checkpoint_file=str(ckpt),
                       checkpoint_every=CKPT_EVERY, resume=resuming)
    sampler.save(str(out_path))

    # Only reached once out_path is written, so the run is safely persisted.
    try:
        ckpt.unlink()
    except OSError:
        pass
    return sampler


