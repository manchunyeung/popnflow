    GRID_M4 = 500

    @partial(jit, static_argnums=(0,))
    def m1_m2_samples_rosenblatt(n_samples, m_min_1=5.0, m_max_1=100.0, alpha_1=1.0,
                                 beta=0.5, mu=30.0, sigma=1.0, f=0.1, u1=None, u2=None):
        m1_grid = jnp.linspace(m_min_1 + 0.01, m_max_1, GRID_M4)
        m2_grid = jnp.linspace(m_min_1 + 0.01, m_max_1, GRID_M4)
        m1g, m2g = jnp.meshgrid(m1_grid, m2_grid, indexing="ij")
