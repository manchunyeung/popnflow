# ── Load per-event best-K table ───────────────────────────────────────────
def _load_k_table(path, column):
    names, ks = [], []
    with open(path, newline="") as fh:
        reader = _csv.DictReader(fh)
        if "event" not in reader.fieldnames or column not in reader.fieldnames:
            raise ValueError(
                f"--kfile must contain 'event' and '{column}' columns; "
                f"found {reader.fieldnames}")
        for row in reader:
            names.append(row["event"])
            ks.append(int(float(row[column])))
    return names, ks

import numpy as np  # needed here: _load_gmm_table runs eagerly below, before
                     # the file's main `import numpy as np` (line ~305/696)


class _LoadedGMM:
    """Stand-in for a fitted sklearn GaussianMixture, built from arrays saved
    by sim_cat_fit_event_gmms.py. Exposes exactly what sim_cat_inference.py's
    per-event GMM code touches: weights_/means_/precisions_/precisions_cholesky_
    (for gmm_logpdf_optimized) and .sample() (for the leakage diagnostic).
    .sample() is NOT byte-identical to sklearn's own RNG stream -- it is a
    plain numpy re-implementation of the same generative model (draw a
    component from `weights_`, then a Gaussian from that component's mean/
    covariance) -- fine for a Monte Carlo leakage estimate, not intended for
    reproducing a specific sklearn sample() call bit-for-bit.
    """
    def __init__(self, weights, means, covariances, precisions, precisions_cholesky):
        self.weights_ = np.asarray(weights, dtype=np.float64)
        self.means_ = np.asarray(means, dtype=np.float64)
        self.covariances_ = np.asarray(covariances, dtype=np.float64)
        self.precisions_ = np.asarray(precisions, dtype=np.float64)
        self.precisions_cholesky_ = np.asarray(precisions_cholesky, dtype=np.float64)

    def sample(self, n_samples, rng=None):
        rng = rng or np.random.default_rng()
        K = len(self.weights_)
        counts = rng.multinomial(n_samples, self.weights_ / self.weights_.sum())
        X, y = [], []
        for k in range(K):
            if counts[k] == 0:
                continue
            X.append(rng.multivariate_normal(self.means_[k], self.covariances_[k],
                                              size=counts[k]))
            y.append(np.full(counts[k], k))
        return np.concatenate(X, axis=0), np.concatenate(y, axis=0)


def _load_gmm_table(path, kcol):
    """pool-index-string -> _LoadedGMM, for the K choice named by --kcol
    (k_argmin -> the file's 'argmin' group, k_plateau -> 'plateau').
    Local import: the file-wide `import h5py` (below) comes later in this
    script than this function is defined."""
    import h5py
    tag = {"k_argmin": "argmin", "k_plateau": "plateau"}.get(kcol, kcol)
    table = {}
    with h5py.File(path, "r") as f:
        for grp_name in f:
            grp = f[grp_name]
            if tag not in grp:
                raise KeyError(f"{path} group '{grp_name}' has no '{tag}' subgroup "
                               f"(from --kcol={kcol!r}); available: {list(grp.keys())}")
            sub = grp[tag]
            gmm = _LoadedGMM(sub["weights"][:], sub["means"][:], sub["covariances"][:],
                             sub["precisions"][:], sub["precisions_cholesky"][:])
            table[str(int(grp.attrs["pool_index"]))] = gmm
            table[str(grp.attrs["event_name"])] = gmm
    return table


