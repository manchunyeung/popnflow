# zMax sets the support over which dV_of_z_normed normalises p(z|gamma), so it
# MUST match the z_max the catalog was generated with (sim_cat: 1.9, which is
# also endo3_v12's max_redshift and the injection set's z_ref_max).  The parent
# script used 2.0 against a population generated at 1.9; that mismatch mostly
# cancels between the per-event and selection terms (both carry the same
# 1/N(gamma)), but it leaves the model with support the injections never cover,
# and it makes the printed xi disagree with sim_cat_06_validate.py's check 2 by
# exactly Z(1.9)/Z(2.0) = 0.870.  Matching it removes the ambiguity entirely.
zMax = args.z_max
zgrid = jnp.expm1(np.linspace(np.log(1), np.log(zMax+1), 10000))
Om0grid = jnp.linspace(0,1,1000)

rs = []
for Om0 in tqdm(Om0grid):
    cosmo = FlatLambdaCDM(H0=H0Planck,Om0=Om0)
    rs.append(cosmo.comoving_distance(zgrid).to(u.Mpc).value)

rs = jnp.asarray(rs)
rs = rs.reshape(len(Om0grid),len(zgrid))

@jit
def E(z,Om0=Om0Planck):
    return jnp.sqrt(Om0*(1+z)**3 + (1.0-Om0))

@jit
def r_of_z(z,H0,Om0=Om0Planck):
    return interp2d(Om0,z,Om0grid,zgrid,rs)*(H0Planck/H0)

@jit
def dL_of_z(z,H0,Om0=Om0Planck):
    return (1+z)*r_of_z(z,H0,Om0)

@jit
def z_of_dL(dL,H0,Om0=Om0Planck):
    return jnp.interp(dL,dL_of_z(zgrid,H0,Om0),zgrid)

@jit
def dV_of_z(z,H0,Om0=Om0Planck):
    return speed_of_light*r_of_z(z,H0,Om0)**2/(H0*E(z,Om0))

@jit
def ddL_of_z(z,dL,H0,Om0=Om0Planck):
    return dL/(1+z) + speed_of_light*(1+z)/(H0*E(z,Om0))

