        Z = jnp.trapezoid(pdf_unnorm, _z_vals_m4)
        pdf = pdf_unnorm / jnp.maximum(Z, jnp.finfo(pdf_unnorm.dtype).tiny)
        cdf = _cumtrapz_y(pdf, _dz_m4); cdf = cdf / jnp.maximum(cdf[-1], jnp.finfo(cdf.dtype).tiny)
        eps = jnp.finfo(cdf.dtype).eps
        u = jnp.clip(u, 0.0, 1.0 - eps)
        i_hi = jnp.clip(jnp.searchsorted(cdf, u, side="left"), 1, N_GRID_M4 - 1)
        i_lo = i_hi - 1
        t = (u - cdf[i_lo]) / jnp.maximum(cdf[i_hi] - cdf[i_lo], eps)
        return _z_vals_m4[i_lo] + t * (_z_vals_m4[i_hi] - _z_vals_m4[i_lo])

