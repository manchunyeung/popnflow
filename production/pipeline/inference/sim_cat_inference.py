@jit
def logpm1m2_plpeak_massratio(
    m1, m2,
    m_min_1, m_max_1,
    alpha_1,
    beta, mu, sigma,
    f
):
    q = m2/m1
    alpha_1 = -alpha_1
    # --- p(m1): Power-law component ---
    norm_pl = (m_max_1**(1. + alpha_1) - m_min_1**(1. + alpha_1))
    p_m1_pl = (1. + alpha_1) * m1**alpha_1 / norm_pl

    # Mask out-of-range m1
    p_m1_pl = jnp.where(m1 > m_max_1, 0.0, p_m1_pl)
    p_m1_pl = jnp.where(m1 < m_min_1, 0.0, p_m1_pl)

    # --- p(m1): Peak component ---
    p_m1_peak = jnp.exp(-0.5 * (m1 - mu)**2 / sigma**2) / jnp.sqrt(2. * jnp.pi * sigma**2)

    # TRUNCATE_PEAK: match the GENERATOR's support exactly.
    # sim_cat_03_generate_pool.draw_population builds its m1 grid on
    # [m_min, m_max] and renormalises (`cdf /= cdf[-1]`), so its Gaussian peak
    # is truncated.  This function historically did NOT truncate, leaving
    # likelihood density above m_max that the generator can never produce.  On
    # [m_min, m_max] both share a functional form, so the difference is only a
    # Lambda-dependent constant -- which cancels between the per-event product
    # and xi^N -- but xi(Lambda) integrates injections ABOVE m_max where the
    # likelihood has support and the truth has none, and that does not cancel.
    #
    # The effect is 0.000% at the fixed-Lambda MDC point (the peak sits 8.8
    # sigma from m_max), which is why model_checks/
    # compare_generation_vs_likelihood.py never saw it -- that check only ever
    # ran at Lambda_MDC.  It scales with (m_max - mu)/sigma and reaches ~4% at
    # ~1 sigma, which matters for the SBC suite, whose Lambda_j are drawn from
    # the whole prior.  See sbc_suite/sbc_00_draw_hyperparams.peak_leak_fraction.
    #
    # DEFAULT OFF so the fixed-Lambda pipeline is bit-for-bit unchanged.
    if TRUNCATE_PEAK:
        p_m1_peak = jnp.where(m1 > m_max_1, 0.0, p_m1_peak)
        p_m1_peak = jnp.where(m1 < m_min_1, 0.0, p_m1_peak)

    # Mixture
    p_m1 = f * p_m1_peak + (1. - f) * p_m1_pl

    # --- p(q | m1): mass-ratio power law ---
    q_min = m_min_1/m1
    denom = Q_MAX**(1. + beta) - q_min**(1. + beta)
    p_q = (1. + beta) * q**beta / denom

    # Enforce m2 >= m_min_1
    p_q = jnp.where(q*m1 < m_min_1, 0.0, p_q)
    # Restrict to q <= Q_MAX (no-op at the default Q_MAX = 1.0)
    p_q = jnp.where(q > Q_MAX, 0.0, p_q)

    # --- log joint ---
    return jnp.log(p_m1) + jnp.log(p_q) - jnp.log(m1)

@jit
def _plpeak_unnormalised(m, m_min_1, m_max_1, alpha_1, mu, sigma, f):
    """PL+Peak mixture for p(m1), BEFORE any window or renormalisation.

    Same algebra as the p_m1 block of `logpm1m2_plpeak_massratio` above, factored
    out so the sharp and smoothed models cannot drift apart.  As there, the
    Gaussian component is truncated at [m_min_1, m_max_1] only when
    TRUNCATE_PEAK is set (default off; see that function for why).
    """
    a = -alpha_1
    norm_pl = (m_max_1**(1. + a) - m_min_1**(1. + a))
    p_pl = (1. + a) * m**a / norm_pl
    p_pl = jnp.where(m > m_max_1, 0.0, p_pl)
    p_pl = jnp.where(m < m_min_1, 0.0, p_pl)
    p_peak = jnp.exp(-0.5 * (m - mu)**2 / sigma**2) / jnp.sqrt(2. * jnp.pi * sigma**2)
    if TRUNCATE_PEAK:
        p_peak = jnp.where(m > m_max_1, 0.0, p_peak)
        p_peak = jnp.where(m < m_min_1, 0.0, p_peak)
    return f * p_peak + (1. - f) * p_pl

@jit
def logpm1m2_plpeak_massratio_smoothed(
    m1, m2,
    m_min_1, m_max_1,
    alpha_1,
    beta, mu, sigma,
    f, delta_m
):
    """Smoothed PL+Peak: the likelihood-side counterpart of the model the
    sim_cat2 catalogs were generated from.

    Mirrors gwpopulation's `SinglePeakSmoothedMassDistribution`, which
    `sim_cat_03_generate_pool.py::draw_population_smoothed` calls directly:
    the Talbot & Thrane 2018 window S(m) rises from 0 to 1 over
    [m_min, m_min+delta_m] and multiplies BOTH m1 and m2, killing the low-mass
    corner where the sharp model piles up events (see that function's docstring
    for the measured ~8x excess).  Reuses `Sfilter_low` above, which is already
    that same window and is jnp.where-based, hence jit-safe -- gwpopulation's
    own `smoothing()` uses boolean mask indexing and will not trace.

    Both normalisations are numerical: applying S breaks the closed-form
    `norm_pl` and the `1 - q_min**(1+beta)` denominator the sharp model uses.
    Where a normalisation integrates to zero -- e.g. m1 barely above m_min, so
    the window leaves no room for m2 -- the density is set to 0 rather than
    dividing by zero.  That zero is the physically meaningful answer and is
    exactly the suppression this model exists to impose.
    """
    q = m2/m1

    # --- p(m1): PL+Peak * window, renormalised over the `mass` grid ---
    p_m1 = (_plpeak_unnormalised(m1, m_min_1, m_max_1, alpha_1, mu, sigma, f)
            * Sfilter_low(m1, m_min_1, delta_m))
    norm_m1 = jnp.trapezoid(
        _plpeak_unnormalised(mass, m_min_1, m_max_1, alpha_1, mu, sigma, f)
        * Sfilter_low(mass, m_min_1, delta_m), mass)
    p_m1 = jnp.where(norm_m1 > 0.0, p_m1 / norm_m1, 0.0)

    # --- p(q|m1): q^beta * window on m2, renormalised per m1 ---
    # The q<=1 (i.e. m2<=m1) edge that gwpopulation passes as mmax=m1 is already
    # enforced by the `mass_ratio` grid and by the m2<m1 mask in log_p_pop_lvk.
    _M = _SM_M1_GRID[:, None]
    _Q = _SM_Q_GRID[None, :]
    norm_q_grid = jnp.trapezoid(
        _Q**beta * Sfilter_low(_M * _Q, m_min_1, delta_m), _SM_Q_GRID, axis=-1)
    norm_q = jnp.interp(m1, _SM_M1_GRID, norm_q_grid)
    p_q = q**beta * Sfilter_low(m2, m_min_1, delta_m)
    p_q = jnp.where(norm_q > 0.0, p_q / norm_q, 0.0)

    # log joint, with the dq/dm2 = 1/m1 Jacobian (as in the sharp model)
    return jnp.log(p_m1) + jnp.log(p_q) - jnp.log(m1)

@jit
def log_p_pop_lvk(m1,m2,z,gamma, m_min_1,m_max_1,alpha_1,beta,mu,sigma,f1,delta_m=0.0):
    # SMOOTHED_MASS is a Python bool, so only one branch is ever traced and the
    # sharp path is bit-for-bit what it was before delta_m existed.  delta_m is
    # ignored entirely when sharp.
    if SMOOTHED_MASS:
        log_pm1m2 = logpm1m2_plpeak_massratio_smoothed(
            m1, m2, m_min_1, m_max_1, alpha_1, beta, mu, sigma, f1, delta_m)
    else:
        log_pm1m2 = logpm1m2_plpeak_massratio(m1, m2, m_min_1, m_max_1, alpha_1, beta, mu, sigma, f1)
    log_pz = jnp.log(dV_of_z_normed(z,Om0Planck,gamma))
    log_p = log_pm1m2 + log_pz
    log_p = jnp.where(m2<m1, log_p, -jnp.inf)
    return log_p

