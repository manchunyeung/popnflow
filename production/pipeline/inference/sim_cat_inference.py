#!/usr/bin/env python
"""
sim_cat_inference.py
=====================
Hierarchical population inference on the GWMockCat catalogs in `sim_cat/`.

Derived from `mdc_inference_multicatalog.py`; the population models, the three
likelihoods (Methods 1/3/4), the per-event GMM machinery and the dynesty setup
are unchanged.  What differs is the DATA and the SELECTION FUNCTION:

  * Events come from `sim_cat/mdc_cat{ID:03d}.h5` -- per-event groups holding
    5000 mock PE samples in DETECTOR frame (`m1_det`, `m2_det`, `dL`, `z`,
    `prior`).  The catalog membership was fixed at generation time
    (`sim_cat/mdc_membership.npy`), so no event subset is drawn here; the
    catalog file IS the subset.  Per-event GMMs are still fitted in
    (m1_det, m2_det, dL) and transformed back to source frame, which is the
    whole point of the study.

  * The selection function comes from `sim_cat/injections.h5`, the MATCHED
    injection set generated by the same rho_obs machinery, same H1+L1
    O3-actual SNR grid, same Finn & Chernoff Theta and the same rho_obs >= 9
    threshold as the events (see sim_cat/RUN_NOTES.md).

SELECTION FUNCTION -- important difference from the parent script.
`mdc_inference_multicatalog.py` reconstructed the endo3 draw density
ANALYTICALLY (`log_p_injection_prior`) for Method 1/4, and for Method 3 fitted
a GMM to the found injections and drew fresh points from it.  Both routes are
sources of the constant-offset bug documented in CLAUDE_CODE_TASK_selection.md
(endo3's stored `sampling_pdf` is the full joint INCLUDING spins, so dividing
by it leaves an uncancelled spin-volume factor).

`sim_cat/injections.h5` instead stores the EXACT marginal draw density over
(m1_src, m2_src, z) and nothing else -- no spin, no angle factors -- so all
three methods here divide by that stored density directly:

    xi(Lambda) = (1/N_total_drawn) * sum_{detected} p_pop(theta|Lambda) / sampling_pdf

No analytic reconstruction, no selection GMM.  Methods 1 and 3 therefore differ
ONLY in the per-event treatment (direct PE-sample sum vs. GMM importance
sampling), which is exactly the comparison the study is about.

PE PRIOR.  The catalogs' stored `prior` column is dL^2 in detector-frame
coordinates (uniform in detector-frame component masses, p(dL) ~ dL^2 -- the
standard LVK convention).  Converting to the source-frame (m1,m2,z)
coordinates the population model lives in contributes the usual
    - log(ddL/dz) - 2 log(1+z) - 2 log(dL)
which is precisely the term the parent script already applies, so that code is
reused verbatim rather than reading the stored column.

Usage
-----
python sim_cat_inference.py --indir sim_cat --outdir sim_cat/inference \
       --catalog-id 0 --method all --live-points 1000
"""
