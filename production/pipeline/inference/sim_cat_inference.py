# the low-mass window multiplies m2, p(q|m1) loses the closed-form normalisation
# the sharp model uses, so it has to be re-integrated on a 2D (m1, q) grid at
# EVERY likelihood call -- it depends on m_min, beta and delta_m, all of which
# the sampler moves.  Shape follows gwpopulation's SinglePeakSmoothedMassDist-
# ribution default normalization_shape=(1000, 500); the coarser grid (vs the
